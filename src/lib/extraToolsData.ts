import type { ToolDefinition, CategorySlug } from './tools';

interface CompactToolSeed {
  slug: string;
  name: string;
  category: string;
  categorySlug: CategorySlug;
  shortDescription: string;
  seoTitle: string;
  metaDescription: string;
  keywords: string[];
  iconName: string;
  dateAdded: string;
  isPopular?: boolean;
  isMostUsed?: boolean;
  isFileTool?: boolean;
  howTo: string[];
  faqs: { question: string; answer: string }[];
  relatedSlugs: string[];
  overview: string[];
  bestPractices: string[];
}

function buildTool(seed: CompactToolSeed): ToolDefinition {
  return {
    slug: seed.slug,
    name: seed.name,
    category: seed.category,
    categorySlug: seed.categorySlug,
    shortDescription: seed.shortDescription,
    seoTitle: seed.seoTitle,
    metaDescription: seed.metaDescription,
    keywords: seed.keywords,
    iconName: seed.iconName,
    dateAdded: seed.dateAdded,
    isPopular: seed.isPopular,
    isMostUsed: seed.isMostUsed,
    isFileTool: seed.isFileTool,
    howTo: seed.howTo,
    faqs: seed.faqs,
    relatedSlugs: seed.relatedSlugs,
    guideSections: [
      {
        heading: `How the ${seed.name} Works`,
        paragraphs: seed.overview,
      },
      {
        heading: `Practical Tips & Best Practices for ${seed.name}`,
        paragraphs: seed.bestPractices,
      },
    ],
  };
}

